//directly export functions

module.exports.add = function(num1,num2){
    //local variable
    let result = num1 + num2;
    return result;
}

module.exports.sub = function(num1,num2){
    //local variable
    let result = num1 - num2;
    return result;
}

module.exports.mul = function(num1,num2){
    //local variable
    let result = num1 * num2;
    return result;
}

module.exports.div = function(num1,num2){
    //local variable
    let result = num1 / num2;
    return result;
}